"""Append-only governance history. Private writers preserve the real actor."""
import json

from odoo import api, fields, models, _
from odoo.exceptions import AccessError

_AUDIT_TOKEN = object()


class EhAccessAudit(models.Model):
    _name = "eh.access.audit"
    _description = "Access Studio Governance Audit"
    _order = "id desc"
    _rec_name = "event"

    event = fields.Char(required=True, readonly=True, index=True)
    occurred_at = fields.Datetime(default=fields.Datetime.now, required=True, readonly=True, index=True)
    actor_id = fields.Many2one("res.users", required=True, readonly=True, ondelete="restrict")
    user_id = fields.Many2one("res.users", readonly=True, ondelete="set null", index=True)
    company_id = fields.Many2one("res.company", required=True, readonly=True, ondelete="restrict", index=True)
    resource_model = fields.Char(required=True, readonly=True)
    resource_id = fields.Integer(required=True, readonly=True)
    resource_name = fields.Char(readonly=True)
    details = fields.Text(readonly=True)

    @api.model
    def _record(self, event, resource, user=None, details=None):
        resource.ensure_one()
        return self.sudo().with_context(_eh_audit_token=_AUDIT_TOKEN).create({
            "event": event,
            "actor_id": self.env.uid,
            "user_id": user.id if user else False,
            "company_id": resource.company_id.id,
            "resource_model": resource._name,
            "resource_id": resource.id,
            "resource_name": resource.display_name,
            "details": json.dumps(details or {}, ensure_ascii=False, sort_keys=True, default=str),
        })

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get("_eh_audit_token") is not _AUDIT_TOKEN:
            raise AccessError(_("Audit entries are generated by Access Studio operations."))
        return super().create(vals_list)

    def write(self, vals):
        raise AccessError(_("Access Studio audit entries cannot be changed."))

    def unlink(self):
        raise AccessError(_("Access Studio audit entries cannot be deleted."))
