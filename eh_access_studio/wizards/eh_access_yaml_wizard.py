SCHEMA_VERSION = 2
PROFILE_SCALAR_FIELDS = (
    "name", "sequence", "active", "readonly", "apply_to_all_companies",
    "date_from", "date_until", "hide_chatter", "hide_send_message", "hide_log_note",
    "hide_schedule_activity", "hide_import", "hide_export", "hide_spreadsheet",
    "hide_add_property", "disable_login", "disable_debug_mode",
    "hide_custom_filter", "hide_custom_group", "restrict_module_management",
)
MODEL_FLAGS = (
    "restrict_create", "restrict_edit", "restrict_delete", "restrict_archive",
    "restrict_duplicate", "restrict_import", "restrict_export", "restrict_spreadsheet",
    "restrict_add_property", "hide_search_panel",
)
FIELD_FLAGS = ("invisible", "readonly", "required", "hide_external_link")
DOMAIN_FLAGS = ("read_right", "create_right", "write_right", "delete_right", "apply_filter", "soft_restrict")
LINE_SPECS = (
    ("field_line_ids", "field_lines", "eh.access.field"),
    ("model_line_ids", "model_lines", "eh.access.model"),
    ("node_line_ids", "node_lines", "eh.access.node"),
    ("chatter_line_ids", "chatter_lines", "eh.access.chatter"),
    ("domain_line_ids", "domain_lines", "eh.access.domain"),
)


class _PolicyLoader(yaml.SafeLoader):
    """Reject ambiguous duplicate keys while retaining safe YAML scalars."""

    def construct_mapping(self, node, deep=False):
        self.flatten_mapping(node)
        mapping = {}
        for key_node, value_node in node.value:
            key = self.construct_object(key_node, deep=deep)
            if not isinstance(key, str):
                raise yaml.constructor.ConstructorError(None, None, "Policy keys must be text", key_node.start_mark)
            if key in mapping:
                raise yaml.constructor.ConstructorError(None, None, "Duplicate policy key: %s" % key, key_node.start_mark)
            mapping[key] = self.construct_object(value_node, deep=deep)
        return mapping


def _check_yaml_shape(value, ancestors=None, depth=0):
    if depth > 30:
        raise UserError(_("Policy nesting exceeds the supported limit."))
    if not isinstance(value, (dict, list)):
        return
    ancestors = set() if ancestors is None else ancestors
    if id(value) in ancestors:
        raise UserError(_("YAML aliases that reuse mappings or lists are not allowed in policies."))
    ancestors.add(id(value))
    for member in (value.values() if isinstance(value, dict) else value):
        _check_yaml_shape(member, ancestors, depth + 1)


def _canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)


def _digest(value):
    return hashlib.sha256(_canonical(value).encode()).hexdigest()


class EhAccessYamlWizard(models.TransientModel):
    _name = "eh.access.yaml.wizard"
    _description = "User Access Studio Import / Export"

    mode = fields.Selection([("export", "Export"), ("import", "Import")], required=True, default="export")
    profile_ids = fields.Many2many("eh.access.profile", string="Profiles to export")
    payload = fields.Binary(string="YAML", attachment=False)
    payload_name = fields.Char(default="eh_access_profiles.yaml")
    summary = fields.Text(readonly=True)
    preview_digest = fields.Char(readonly=True, copy=False)
    preview_state = fields.Json(readonly=True, copy=False)
    confirm_active = fields.Boolean(string="Apply changes to active profiles", copy=False)

    def _require_manager(self):
        if not self.env.su and not self.env.user.has_group("eh_access_studio.group_eh_access_manager"):
            raise AccessError(_("Only Access Studio managers can import, export or restore policies."))

    @api.model_create_multi
    def create(self, vals_list):
        self._require_manager()
        if any(set(vals) & {"preview_digest", "preview_state"} for vals in vals_list):
            raise AccessError(_("Preview evidence is generated by validation and cannot be supplied."))
        vals_list = [dict(vals, payload=vals["payload"].decode("ascii")) if isinstance(vals.get("payload"), bytes) else vals for vals in vals_list]
        return super().create(vals_list)

    def write(self, vals):
        self._require_manager()
        if set(vals) & {"preview_digest", "preview_state"}:
            raise AccessError(_("Preview evidence cannot be edited. Validate the file again."))
        if "payload" in vals:
            vals = dict(vals, preview_digest=False, preview_state=False, confirm_active=False)
            if isinstance(vals["payload"], bytes):
                vals["payload"] = vals["payload"].decode("ascii")
        return super().write(vals)

    def _dialog(self):
        return {"type": "ir.actions.act_window", "res_model": self._name,
                "res_id": self.id, "view_mode": "form", "target": "new"}

    def action_export(self):
        self._require_manager()
        self.ensure_one()
        if not self.profile_ids:
            raise UserError(_("Pick at least one profile to export."))
        data = {"schema_version": SCHEMA_VERSION,
                "profiles": [self._serialise_profile(p) for p in self.profile_ids]}
        self.write({"payload": base64.b64encode(yaml.safe_dump(data, sort_keys=False, allow_unicode=True).encode()),
                    "summary": _("Exported %s profile(s), schema version 2.", len(self.profile_ids))})
        return self._dialog()

    def _read_payload(self):
        self._require_manager()
        self.ensure_one()
        if not self.payload:
            raise UserError(_("Upload a YAML file first."))
        payload = self.payload
        # Odoo 20 returns BinaryValue with raw contents; earlier versions
        # return base64 bytes. Incoming writes use the common RPC string.
        if hasattr(payload, "content"):
            payload = base64.b64encode(payload.content)
        if len(payload) > 1400000:
            raise UserError(_("YAML payload too large (maximum 1 MB decoded)."))
        try:
            raw = base64.b64decode(payload, validate=True)
            if len(raw) > 1024 * 1024:
                raise UserError(_("YAML payload too large (maximum 1 MB decoded)."))
            parsed = yaml.load(raw.decode("utf-8"), Loader=_PolicyLoader)
            _check_yaml_shape(parsed)
        except (ValueError, UnicodeDecodeError, binascii.Error, yaml.YAMLError) as err:
            raise UserError(_("Invalid UTF-8 YAML file: %s", str(err))) from err
        if not isinstance(parsed, dict) or set(parsed) - {"schema_version", "profiles"}:
            raise UserError(_("YAML root must contain only schema_version and profiles."))
        version = parsed.get("schema_version", 1)
        if type(version) is not int or version not in (1, SCHEMA_VERSION):
            raise UserError(_("Unsupported policy schema version: %s", version))
        entries = parsed.get("profiles")
        if not isinstance(entries, list) or not entries or len(entries) > 200:
            raise UserError(_("profiles must be a non-empty list with at most 200 entries."))
        names = []
        for entry in entries:
            if not isinstance(entry, dict) or not isinstance(entry.get("name"), str) or not entry["name"].strip():
                raise UserError(_("Every profile must be a mapping with a non-empty name."))
            names.append(entry["name"])
        if len(set(names)) != len(names):
            raise UserError(_("A file cannot contain the same profile name twice."))
        return entries

    def action_preview(self):
        self._require_manager()
        self.ensure_one()
        entries = self._read_payload()
        state, diffs = {}, []
        targets = set()
        for entry in entries:
            profile, vals = self._prepare_entry(entry)
            key = str(profile.id) if profile else "new:" + entry["name"]
            if key in targets:
                raise UserError(_("Multiple entries resolve to the same profile."))
            targets.add(key)
            before = self._serialise_profile(profile) if profile else {}
            after = dict(before, **entry)
            state[key] = _digest(before)
            diff = "\n".join(difflib.unified_diff(
                yaml.safe_dump(before, sort_keys=True, allow_unicode=True).splitlines(),
                yaml.safe_dump(after, sort_keys=True, allow_unicode=True).splitlines(),
                fromfile="Current: " + entry["name"], tofile="Proposed: " + entry["name"], lineterm=""))
            diffs.append(diff or _("%s: no policy changes.", entry["name"]))
        # Only this private validation path can publish preview evidence.
        super(EhAccessYamlWizard, self).write({
            "preview_digest": _digest(entries), "preview_state": state, "confirm_active": False,
            "summary": _("Validated references and policy syntax. Review the changes below. Missing keys preserve existing values; null or [] clears optional values.\n\n") + "\n\n".join(diffs),
        })
        return self._dialog()

    def action_import(self):
        self._require_manager()
        self.ensure_one()
        entries = self._read_payload()
        if not self.preview_digest or self.preview_digest != _digest(entries):
            raise UserError(_("Validate and preview this file before applying it."))
        created = updated = 0
        # One savepoint covers the entire file: a failed later entry must
        # not leave an earlier entry applied when an API caller catches it.
        with self.env.cr.savepoint():
            for entry in sorted(entries, key=lambda e: e["name"]):
                profile, vals = self._prepare_entry(entry)
                key = str(profile.id) if profile else "new:" + entry["name"]
                expected = (self.preview_state or {}).get(key)
                if expected is None:
                    raise UserError(_("Profile identity changed since preview. Validate again."))
                self._apply_entry(entry, expected_fingerprint=expected, confirm_active=self.confirm_active,
                                  reason="YAML import")
                updated += bool(profile)
                created += not bool(profile)
            super(EhAccessYamlWizard, self).write({
                "summary": _("Imported: %s created, %s updated. Previous policies saved as revisions.", created, updated),
                "preview_digest": False, "preview_state": False, "confirm_active": False,
            })
        return self._dialog()

    def _reference(self, record):
        # Stable menu paths and action names must not depend on the
        # exporting manager's interface language.
        record = record.with_context(lang=False)
        ref = {"xml_id": record.get_external_id().get(record.id) or None}
        if record._name == "res.users":
            ref["login"] = record.login
        elif record._name == "ir.ui.menu":
            ref["name"] = record.complete_name or record.name
        else:
            ref["name"] = record.with_context(lang=False).name
            if record._name == "ir.actions.report":
                ref.update(model=record.model, report_name=record.report_name)
            elif record._name == "ir.actions.server":
                ref["model"] = record.model_id.model
        return ref

    def _serialise_profile(self, profile):
        self._require_manager()
        profile.ensure_one()
        data = {f: profile[f] for f in PROFILE_SCALAR_FIELDS}
        for key in ("date_from", "date_until"):
            data[key] = data[key].isoformat() if data[key] else None
        data["xml_id"] = profile.get_external_id().get(profile.id) or None
        for key, records in (("users", profile.user_ids), ("companies", profile.company_ids), ("hidden_menus", profile.hidden_menu_ids)):
            data[key] = sorted([self._reference(r) for r in records], key=_canonical)
        data["field_lines"] = [dict(model=l.model_name, fields=sorted(l.field_ids.mapped("name")), condition=l.condition or None,
                                    **{f: l[f] for f in FIELD_FLAGS}) for l in profile.field_line_ids]
        data["model_lines"] = [dict(model=l.model_name, **{f: l[f] for f in MODEL_FLAGS},
                                    hidden_view_types=l.hidden_view_types or None,
                                    hidden_reports=sorted([self._reference(r) for r in l.hidden_report_action_ids], key=_canonical),
                                    hidden_server_actions=sorted([self._reference(r) for r in l.hidden_server_action_ids], key=_canonical))
                               for l in profile.model_line_ids]
        data["node_lines"] = [dict(model=l.model_name, kind=l.kind, target_name=l.target_name,
                                   target_label=l.target_label or None, condition=l.condition or None) for l in profile.node_line_ids]
        data["chatter_lines"] = sorted(profile.chatter_line_ids.mapped("model_name"))
        data["domain_lines"] = [dict(model=l.model_name, **{f: l[f] for f in DOMAIN_FLAGS}, domain=l.domain or "[]") for l in profile.domain_line_ids]
        for _, key, _ in LINE_SPECS:
            data[key] = sorted(data[key], key=_canonical)
        return data

    def _resolve_refs(self, model_name, refs):
        if refs is None:
            return []
        if not isinstance(refs, list):
            raise UserError(_("References for %s must be a list or null.", model_name))
        Model = self.env[model_name].with_context(active_test=False, lang=False)
        ids = []
        for ref in refs:
            if not isinstance(ref, (str, dict)) or not ref:
                raise UserError(_("Invalid reference for %s.", model_name))
            allowed = {"xml_id", "login" if model_name == "res.users" else "name"}
            if model_name in ("ir.actions.report", "ir.actions.server"):
                allowed.add("model")
            if model_name == "ir.actions.report":
                allowed.add("report_name")
            if isinstance(ref, dict) and any(value is not None and not isinstance(value, str) for value in ref.values()):
                raise UserError(_("Reference values must be text or null."))
            if isinstance(ref, dict) and set(ref) - allowed:
                raise UserError(_("Unknown reference keys: %s", ", ".join(sorted(set(ref) - allowed))))
            xmlid = ref.get("xml_id") if isinstance(ref, dict) else (ref if model_name.startswith("ir.actions.") else None)
            try:
                record = self.env.ref(xmlid, raise_if_not_found=False) if xmlid else Model.browse()
            except (ValueError, TypeError) as err:
                raise UserError(_("Invalid external ID: %s", xmlid)) from err
            if record and record._name != model_name:
                raise UserError(_("Reference %s has the wrong model.", xmlid))
            if not record:
                label = (ref.get("login") if model_name == "res.users" else ref.get("name")) if isinstance(ref, dict) else ref
                if not label:
                    raise UserError(_("Missing reference %s on %s; no stable fallback supplied.", xmlid or ref, model_name))
                if model_name == "ir.ui.menu":
                    menus = Model.search([])
                    record = menus.filtered(lambda m: (m.complete_name or m.name) == label)
                    if not record:
                        record = menus.filtered(lambda m: m.name == label)
                else:
                    domain = [("login" if model_name == "res.users" else "name", "=", label)]
                    if isinstance(ref, dict) and ref.get("model"):
                        domain.append(("model_id.model" if model_name == "ir.actions.server" else "model", "=", ref["model"]))
                    if isinstance(ref, dict) and ref.get("report_name"):
                        domain.append(("report_name", "=", ref["report_name"]))
                    record = Model.search(domain, limit=2)
            if len(record) != 1:
                raise UserError(_("Reference %s on %s is missing or ambiguous. No policy was applied.", ref, model_name))
            ids.append(record.id)
        return sorted(set(ids))

    def _prepare_entry(self, entry):
        """Resolve and validate a portable policy without writing records."""
        self._require_manager()
        if not isinstance(entry, dict):
            raise UserError(_("A policy must be a mapping."))
        allowed = set(PROFILE_SCALAR_FIELDS) | {"xml_id", "users", "companies", "hidden_menus"} | {s[1] for s in LINE_SPECS}
        unknown = set(entry) - allowed
        if unknown:
            raise UserError(_("Unknown policy keys: %s", ", ".join(sorted(unknown))))
        if not isinstance(entry.get("name"), str) or not entry["name"].strip():
            raise UserError(_("A policy requires a non-empty name."))
        Profile = self.env["eh.access.profile"].with_context(active_test=False)
        if entry.get("xml_id") is not None and not isinstance(entry.get("xml_id"), str):
            raise UserError(_("Profile external ID must be text or null."))
        try:
            profile = self.env.ref(entry["xml_id"], raise_if_not_found=False) if entry.get("xml_id") else Profile.browse()
        except (ValueError, TypeError) as err:
            raise UserError(_("Invalid profile external ID.")) from err
        if profile and profile._name != "eh.access.profile":
            raise UserError(_("Profile external ID resolves to another model."))
        if not profile:
            profile = Profile.search([("name", "=", entry["name"])], limit=2)
        if len(profile) > 1:
            raise UserError(_("Profile name is ambiguous: %s", entry["name"]))
        vals = {}
        for key in PROFILE_SCALAR_FIELDS:
            if key not in entry:
                continue
            value = entry[key]
            if Profile._fields[key].type == "boolean":
                if value is not None and type(value) is not bool:
                    raise UserError(_("%s must be true, false or null.", key))
                value = bool(value)
            elif key == "sequence":
                if type(value) is not int:
                    raise UserError(_("sequence must be an integer."))
            elif key in ("date_from", "date_until"):
                try:
                    value = fields.Date.to_date(value) if value else False
                except (TypeError, ValueError) as err:
                    raise UserError(_("%s must be an ISO date or null.", key)) from err
            vals[key] = value
        start = vals.get("date_from", profile.date_from if profile else False)
        end = vals.get("date_until", profile.date_until if profile else False)
        if start and end and start > end:
            raise UserError(_("Active From cannot be after Active Until."))
        for key, field, model in (("users", "user_ids", "res.users"), ("companies", "company_ids", "res.company"), ("hidden_menus", "hidden_menu_ids", "ir.ui.menu")):
            if key in entry:
                vals[field] = [(6, 0, self._resolve_refs(model, entry[key]))]
        for field, key, model_name in LINE_SPECS:
            if key not in entry:
                continue
            raws = entry[key] if entry[key] is not None else []
            if not isinstance(raws, list) or len(raws) > 2000:
                raise UserError(_("%s must be a list of at most 2000 rules or null.", key))
            vals[field] = [(5, 0, 0)] + [(0, 0, self._line_values(model_name, raw)) for raw in raws]
        # Run profile invariants on a virtual record; no chatter, sequence,
        # database or live policy changes are made during preview.
        virtual_vals = {f: profile[f] for f in PROFILE_SCALAR_FIELDS} if profile else {}
        virtual_vals.update(vals)
        virtual_vals["user_ids"] = vals.get("user_ids", [(6, 0, profile.user_ids.ids if profile else [])])
        virtual = Profile.new(virtual_vals)
        virtual._check_no_admin_in_readonly()
        return profile, vals

    def _line_values(self, model_name, raw):
        if model_name == "eh.access.chatter" and isinstance(raw, str):
            raw = {"model": raw}
        if not isinstance(raw, dict):
            raise UserError(_("Rule must be a mapping."))
        extras = {
            "eh.access.field": set(FIELD_FLAGS) | {"fields", "condition"},
            "eh.access.model": set(MODEL_FLAGS) | {"hidden_view_types", "hidden_reports", "hidden_server_actions"},
            "eh.access.node": {"kind", "target_name", "target_label", "condition"},
            "eh.access.chatter": set(),
            "eh.access.domain": set(DOMAIN_FLAGS) | {"domain"},
        }[model_name]
        unknown = set(raw) - extras - {"model"}
        if unknown:
            raise UserError(_("Unknown rule keys: %s", ", ".join(sorted(unknown))))
        model = self.env["ir.model"].search([("model", "=", raw.get("model"))], limit=1)
        if not model or model.model not in self.env:
            raise UserError(_("Unknown or unavailable model: %s", raw.get("model")))
        vals = {"model_id": model.id}
        for key in extras - {"fields", "hidden_reports", "hidden_server_actions"}:
            if key in raw:
                value = raw[key]
                field = self.env[model_name]._fields[key]
                if field.type == "boolean":
                    if value is not None and type(value) is not bool:
                        raise UserError(_("%s must be true, false or null.", key))
                    value = bool(value)
                elif value is not None and not isinstance(value, str):
                    raise UserError(_("%s must be text or null.", key))
                vals[key] = value or False
        if model_name == "eh.access.field":
            names = raw.get("fields")
            if not isinstance(names, list) or not names or any(not isinstance(n, str) for n in names):
                raise UserError(_("A field rule requires a non-empty fields list."))
            found = self.env["ir.model.fields"].search([("model_id", "=", model.id), ("name", "in", names)])
            if set(found.mapped("name")) != set(names):
                raise UserError(_("Unknown fields on %s: %s", model.model, ", ".join(sorted(set(names) - set(found.mapped("name"))))))
            vals["field_ids"] = [(6, 0, found.ids)]
        if model_name == "eh.access.model":
            for key, field, target in (("hidden_reports", "hidden_report_action_ids", "ir.actions.report"), ("hidden_server_actions", "hidden_server_action_ids", "ir.actions.server")):
                vals[field] = [(6, 0, self._resolve_refs(target, raw.get(key)))]
        condition = vals.get("condition")
        if condition:
            try:
                tree = ast.parse(condition, mode="eval")
            except SyntaxError as err:
                raise UserError(_("Invalid rule condition: %s", str(err))) from err
            permitted = (ast.Expression, ast.BoolOp, ast.UnaryOp, ast.Compare, ast.Name, ast.Load, ast.Constant,
                         ast.And, ast.Or, ast.Not, ast.Eq, ast.NotEq, ast.Lt, ast.LtE, ast.Gt, ast.GtE,
                         ast.In, ast.NotIn, ast.Is, ast.IsNot, ast.List, ast.Tuple, ast.BinOp, ast.Add, ast.Sub,
                         ast.Mult, ast.Div, ast.Mod, ast.USub, ast.UAdd)
            if any(not isinstance(node, permitted) for node in ast.walk(tree)):
                raise UserError(_("Conditions may use fields, comparisons and arithmetic only; calls and attributes are not allowed."))
            names = {n.id for n in ast.walk(tree) if isinstance(n, ast.Name)}
            if names - set(self.env[model.model]._fields):
                raise UserError(_("Condition names unknown fields: %s", ", ".join(sorted(names - set(self.env[model.model]._fields)))))
        virtual = self.env[model_name].new(vals)
        if model_name == "eh.access.field":
            virtual._check_at_least_one_effect()
            virtual._check_not_invisible_and_required()
        elif model_name == "eh.access.model":
            virtual._check_hidden_view_types()
        elif model_name == "eh.access.node":
            if not vals.get("target_name"):
                raise UserError(_("A node rule requires target_name."))
            virtual._check_target_name()
        elif model_name == "eh.access.domain":
            virtual._check_domain_parses()
        return vals

    def _apply_entry(self, entry, expected_fingerprint, confirm_active=False, reason="Policy apply"):
        """Private atomic API for reviewed import/AI drafts; expected state is mandatory."""
        self._require_manager()
        with self.env.cr.savepoint():
            return self._apply_entry_locked(entry, expected_fingerprint, confirm_active, reason)

    def _apply_entry_locked(self, entry, expected_fingerprint, confirm_active, reason):
        self._require_manager()
        Revision = self.env["eh.access.revision"]
        # The shared policy/governance lock precedes per-name and row locks,
        # including when a batch imports multiple names in a different order.
        self.env["eh.access.profile"]._eh_lock_policy()
        # Serialize creation by natural identity too; profile uniqueness is a
        # Python constraint and otherwise two concurrent imports could race.
        lock_id = int(hashlib.sha256(entry["name"].encode()).hexdigest()[:15], 16)
        self.env.cr.execute("SELECT pg_advisory_xact_lock(%s)", (lock_id,))
        profile, vals = self._prepare_entry(entry)
        if profile:
            Revision._lock_profile(profile)
            profile, vals = self._prepare_entry(entry)
        current = Revision._policy_fingerprint(profile) if profile else _digest({})
        if not expected_fingerprint or current != expected_fingerprint:
            raise UserError(_("Policy changed since preview. Review a fresh comparison before applying."))
        active = vals.get("active", profile.active if profile else True)
        if (active or (profile and profile.active)) and not confirm_active:
            raise UserError(_("Confirm changes to active profiles before applying."))
        if profile:
            Revision._snapshot(profile, reason + " — before")
            profile.write(vals)
        else:
            # Name uniqueness is enforced by the profile model; serialization
            # failures roll back the complete enclosing import transaction.
            profile = self.env["eh.access.profile"].create(vals)
        Revision._snapshot(profile, reason + " — after")
        return profile
